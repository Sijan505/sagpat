// Public endpoints used by the storefront.
import { randomBytes } from "node:crypto";
import express, { Router } from "express";
import { all, one, run, getSettings, productFromRow } from "../db.js";
import { createOrder, getOrder, slotsFor, OrderError } from "../orders.js";
import { rateLimit } from "../auth.js";
import { STATUSES } from "../permissions.js";
import {
  GOOGLE_CLIENT_ID, AuthError, verifyGoogleToken, upsertGoogleUser, createUserSession, destroyUserSession,
  signUpWithPassword, signInWithPassword, requireUser, listNotifications, markNotificationsRead,
} from "../customers.js";

export function publicRoutes({ testimonials }) {
  const router = Router();

  // The storefront's catalog, generated from the database on each request so
  // prices, stock and settings changed in the admin panel show up immediately.
  router.get("/js/data.js", async (_req, res) => {
    const s = await getSettings();
    const categories = await all("SELECT id, ne, en, image FROM categories ORDER BY sort, en");
    const products = (await all("SELECT * FROM products WHERE active = 1 ORDER BY id")).map(productFromRow)
      .map(({ lowStock, active, updatedAt, ...p }) => p);
    const shop = {
      FREE_DELIVERY_OVER: s.free_delivery_over,
      STANDARD_FEE: s.standard_fee,
      EXPRESS_FEE: s.express_fee,
      TAX_RATE: s.tax_rate,
      EXPRESS_CUTOFF_HOUR: s.express_cutoff_hour,
      PHONE: s.phone,
      EMAIL: s.email,
      ACCEPTING_ORDERS: s.accepting_orders,
      GOOGLE_CLIENT_ID,
      SLOTS: {
        standard: (await slotsFor("standard")).map((x) => x.label),
        expressToday: (await slotsFor("express_today")).map((x) => x.label),
        expressTomorrow: (await slotsFor("express_tomorrow")).map((x) => x.label),
      },
    };
    const json = (v) => JSON.stringify(v).replace(/</g, "\\u003c");
    res.type("application/javascript").set("Cache-Control", "no-store").send(
      `// Generated by the Sagpat server from the database.\n` +
      `const CATEGORIES = ${json(categories)};\n` +
      `const PRODUCTS = ${json(products)};\n` +
      `const TESTIMONIALS = ${json(testimonials)};\n` +
      `const SHOP_SETTINGS = ${json(shop)};\n` +
      `function getProduct(id) { return PRODUCTS.find((p) => p.id === Number(id)); }\n` +
      `function getCategory(id) { return CATEGORIES.find((c) => c.id === id); }\n`,
    );
  });

  // Customers must be signed in with Google to order, so every order has an
  // account (order history, notifications)
  const requireSignedInCustomer = (req, res, next) => {
    if (!req.user) return res.status(401).json({ error: "Please sign in to place your order.", signIn: true });
    next();
  };

  router.post("/api/orders", rateLimit({ key: "order", max: 20, windowMs: 10 * 60 * 1000 }), requireSignedInCustomer, async (req, res) => {
    try {
      const order = await createOrder(req.body, req.user.id);
      res.status(201).json(publicOrder(order));
    } catch (err) {
      if (err instanceof OrderError) return res.status(err.status).json({ error: err.message });
      throw err;
    }
  });

  // Customers can view their own order with the private key from the confirmation link
  router.get("/api/orders/:id", async (req, res) => {
    const order = await getOrder(String(req.params.id));
    if (!order || order.accessKey !== String(req.query.key || "")) return res.status(404).json({ error: "Order not found." });
    res.json(publicOrder(order));
  });

  // ---------- Customer accounts (Google sign-in) ----------
  const noStore = async (_req, res, next) => { res.set("Cache-Control", "no-store"); next(); };
  router.use(["/api/auth", "/api/me"], noStore);

  router.post("/api/auth/google", rateLimit({ key: "google", max: 30, windowMs: 10 * 60 * 1000 }), async (req, res) => {
    try {
      const claims = await verifyGoogleToken(req.body?.credential);
      const user = await upsertGoogleUser(claims);
      await destroyUserSession(req, res);
      await createUserSession(res, user.id);
      res.json({ user: publicUser(user) });
    } catch (err) {
      if (err instanceof AuthError) return res.status(err.status).json({ error: err.message });
      throw err;
    }
  });

  // Google's redirect sign-in: after the customer picks an account on Google's
  // page, Google POSTs the signed ID token here as a form, then we send them
  // back to the shop signed in. (No popup window, so it works on phones and
  // with popup blockers.)
  //
  // The "Continue with Google" button is a plain link to /api/auth/google/start,
  // which sends the customer to Google's own sign-in page. Nothing has to load
  // from Google inside our page (no script, no iframe), so it works in in-app
  // browsers (Messenger, Facebook…), with blockers and on slow mobile data.
  // A random value in a short-lived cookie is sent to Google as `state` and
  // `nonce`, and must come back in both the form and the signed token.
  const OAUTH_COOKIE = "sagpat_oauth";
  const callbackUrl = (req) => `${req.protocol}://${req.get("host")}/api/auth/google/callback`;

  router.get("/api/auth/google/start", (req, res) => {
    if (!GOOGLE_CLIENT_ID) return res.redirect(303, `/account.html?signin_error=${encodeURIComponent("Google sign-in isn't set up on this shop yet.")}`);
    const state = randomBytes(24).toString("base64url");
    // Google posts the result back cross-site, so the cookie must be SameSite=None (which needs Secure)
    res.cookie(OAUTH_COOKIE, state, { httpOnly: true, sameSite: "none", secure: true, maxAge: 15 * 60 * 1000, path: "/api/auth/google" });
    const params = new URLSearchParams({
      client_id: GOOGLE_CLIENT_ID,
      redirect_uri: callbackUrl(req),
      response_type: "id_token",
      response_mode: "form_post",
      scope: "openid email profile",
      state,
      nonce: state,
      prompt: "select_account",
    });
    res.redirect(302, `https://accounts.google.com/o/oauth2/v2/auth?${params}`);
  });

  router.post("/api/auth/google/callback", rateLimit({ key: "google", max: 30, windowMs: 10 * 60 * 1000 }),
    express.urlencoded({ extended: false, limit: "20kb" }), async (req, res) => {
      const back = (query) => res.redirect(303, `/account.html${query ? `?${query}` : ""}`);
      const failed = () => back(`signin_error=${encodeURIComponent("Sign-in failed. Please try again.")}`);
      const body = req.body || {};
      let token;
      if (body.id_token || body.error) {
        // From our own link (/api/auth/google/start)
        const expected = req.cookies[OAUTH_COOKIE];
        res.clearCookie(OAUTH_COOKIE, { path: "/api/auth/google", sameSite: "none", secure: true });
        if (body.error === "access_denied") return back(""); // customer cancelled on Google's page
        if (!expected || body.state !== expected || !body.id_token) return failed();
        token = body.id_token;
        res.locals.nonce = expected;
      } else {
        // From Google's own sign-in button (older pages still open in a browser):
        // its CSRF check is that the form field matches the cookie it set
        const formToken = body.g_csrf_token;
        const cookieToken = req.cookies.g_csrf_token;
        if (!formToken || (cookieToken && cookieToken !== formToken)) return failed();
        token = body.credential;
      }
      try {
        const claims = await verifyGoogleToken(token);
        if (res.locals.nonce && claims.nonce !== res.locals.nonce) return failed();
        const user = await upsertGoogleUser(claims);
        await destroyUserSession(req, res);
        await createUserSession(res, user.id);
        back("signed_in=1");
      } catch (err) {
        if (err instanceof AuthError) return back(`signin_error=${encodeURIComponent(err.message)}`);
        throw err;
      }
    });

  // Username + password, for customers whose device can't use Google sign-in
  const passwordAuth = (fn) => async (req, res) => {
    try {
      const user = await fn(req.body || {});
      await destroyUserSession(req, res);
      await createUserSession(res, user.id);
      res.json({ user: publicUser(user) });
    } catch (err) {
      if (err instanceof AuthError) return res.status(err.status).json({ error: err.message });
      throw err;
    }
  };
  router.post("/api/auth/signup", rateLimit({ key: "signup", max: 10, windowMs: 60 * 60 * 1000 }), passwordAuth(signUpWithPassword));
  router.post("/api/auth/login", rateLimit({ key: "login", max: 15, windowMs: 10 * 60 * 1000 }), passwordAuth(signInWithPassword));

  router.post("/api/auth/logout", async (req, res) => {
    await destroyUserSession(req, res);
    res.json({ ok: true });
  });

  router.get("/api/me", async (req, res) => {
    res.json({ user: req.user ? publicUser(req.user) : null, googleEnabled: !!GOOGLE_CLIENT_ID });
  });

  // Order history for the signed-in customer
  router.get("/api/me/orders", requireUser, async (req, res) => {
    const orders = await all(`
      SELECT id, access_key, created_at, status, total, delivery_type, slot, expected_from, expected_to, payment_method, payment_status
      FROM orders WHERE user_id = :u ORDER BY created_at DESC LIMIT 200`, { u: req.user.id });
    const items = await all(`
      SELECT order_id, product_id, ne, en, qty FROM order_items
      WHERE order_id IN (SELECT id FROM orders WHERE user_id = :u)`, { u: req.user.id });
    res.json({
      orders: orders.map((o) => ({
        id: o.id,
        key: o.access_key,
        createdAt: o.created_at,
        status: o.status,
        statusLabel: STATUSES[o.status],
        total: o.total,
        delivery: { type: o.delivery_type, slot: o.slot, from: o.expected_from, to: o.expected_to },
        payment: { method: o.payment_method, status: o.payment_status },
        items: items.filter((i) => i.order_id === o.id).map((i) => ({ productId: i.product_id, ne: i.ne, en: i.en, qty: i.qty })),
      })),
    });
  });

  // Orders placed on this device before signing in (the browser keeps their
  // private links) are added to the account. The key proves they're yours.
  router.post("/api/me/orders/claim", requireUser, async (req, res) => {
    const list = Array.isArray(req.body?.orders) ? req.body.orders.slice(0, 50) : [];
    let claimed = 0;
    for (const o of list) {
      const row = await one("SELECT access_key, user_id FROM orders WHERE id = :id", { id: String(o?.id ?? "") });
      if (row && row.user_id == null && row.access_key === String(o?.key ?? "")) {
        await run("UPDATE orders SET user_id = :u WHERE id = :id", { u: req.user.id, id: String(o.id) });
        claimed++;
      }
    }
    res.json({ claimed });
  });

  router.get("/api/me/notifications", requireUser, async (req, res) => {
    res.json(await listNotifications(req.user.id));
  });

  router.post("/api/me/notifications/read", requireUser, async (req, res) => {
    await markNotificationsRead(req.user.id);
    res.json({ ok: true });
  });

  return router;
}

const publicUser = (u) => ({ name: u.name, email: u.email || "", picture: u.picture, username: u.username || null });

function publicOrder(o) {
  return {
    id: o.id,
    key: o.accessKey,
    createdAt: o.createdAt,
    status: o.status,
    statusLabel: STATUSES[o.status],
    customer: o.customer,
    delivery: o.delivery,
    payment: o.payment,
    totals: o.totals,
    items: o.items,
    // Customers see status changes, not internal staff notes or names
    history: o.events.filter((e) => e.type === "status").map((e) => ({ at: e.at, status: e.status, label: STATUSES[e.status] })),
  };
}
